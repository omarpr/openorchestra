//! Hybrid worktree setup/teardown hooks (committed + local override).
//!
//! Committed defaults live at `<repo_root>/.openorchestra/hooks.toml`, with
//! canonical scripts under `<repo_root>/.openorchestra/scripts/`.
//! Machine-local overrides live at `<data_dir>/hooks/<repo>.toml`, with scripts
//! under `<data_dir>/hooks/<repo>/scripts/`. When a local file exists, its
//! `scripts` lists **replace** the committed lists. Relative paths resolve from
//! the directory holding the TOML that declared them: `<repo_root>/.openorchestra/`
//! for committed, `<data_dir>/hooks/<repo>/` for local.
//!
//! The UI owns script editing; TOML is generated by [`ensure_hook_script`].

use std::collections::HashMap;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use crate::runner::{CommandOutput, CommandRunner};

/// Repo-persisted vs machine-local hook layer.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum HookLayer {
    Repo,
    Local,
}

/// Setup or teardown phase.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum HookScriptPhase {
    Setup,
    Teardown,
}

impl HookScriptPhase {
    pub fn file_name(self) -> &'static str {
        match self {
            HookScriptPhase::Setup => "setup.sh",
            HookScriptPhase::Teardown => "teardown.sh",
        }
    }

    pub fn label(self) -> &'static str {
        match self {
            HookScriptPhase::Setup => "setup",
            HookScriptPhase::Teardown => "teardown",
        }
    }
}

/// One phase of the hook lifecycle.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct HookPhase {
    #[serde(default)]
    pub scripts: Vec<String>,
}

/// Parsed hooks.toml contents.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct HooksFile {
    #[serde(default)]
    pub setup: HookPhase,
    #[serde(default)]
    pub teardown: HookPhase,
}

/// Effective hooks after merge, with scripts resolved to absolute paths.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct HooksConfig {
    pub setup: Vec<PathBuf>,
    pub teardown: Vec<PathBuf>,
}

/// Context passed into hook scripts via the environment.
#[derive(Debug, Clone)]
pub struct HookEnv {
    pub repo_root: PathBuf,
    pub worktree: PathBuf,
    pub branch: String,
    pub task_slug: String,
    pub task_id: Option<String>,
    pub home_worktree: Option<PathBuf>,
}

impl HookEnv {
    pub fn to_map(&self) -> HashMap<String, String> {
        let mut m = HashMap::new();
        m.insert(
            "HARNESS_REPO_ROOT".into(),
            self.repo_root.to_string_lossy().into_owned(),
        );
        m.insert(
            "HARNESS_WORKTREE".into(),
            self.worktree.to_string_lossy().into_owned(),
        );
        m.insert("HARNESS_BRANCH".into(), self.branch.clone());
        m.insert("HARNESS_TASK_SLUG".into(), self.task_slug.clone());
        if let Some(id) = &self.task_id {
            m.insert("HARNESS_TASK_ID".into(), id.clone());
        }
        if let Some(home) = &self.home_worktree {
            m.insert(
                "HARNESS_HOME_WORKTREE".into(),
                home.to_string_lossy().into_owned(),
            );
        }
        m
    }
}

#[derive(Debug)]
pub enum HooksError {
    Io(std::io::Error),
    Parse(String),
    ScriptFailed {
        script: PathBuf,
        status: Option<i32>,
        stderr: String,
    },
}

impl std::fmt::Display for HooksError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            HooksError::Io(e) => write!(f, "{e}"),
            HooksError::Parse(e) => write!(f, "hooks parse error: {e}"),
            HooksError::ScriptFailed {
                script,
                status,
                stderr,
            } => write!(
                f,
                "hook {} failed (status {:?}): {stderr}",
                script.display(),
                status
            ),
        }
    }
}

impl std::error::Error for HooksError {}

impl From<std::io::Error> for HooksError {
    fn from(e: std::io::Error) -> Self {
        HooksError::Io(e)
    }
}

/// Directory holding committed hooks for a repo: `<repo_root>/.openorchestra/`.
pub fn repo_hooks_base(repo_root: &Path) -> PathBuf {
    repo_root.join(".openorchestra")
}

/// Path to the committed hooks file inside a repo.
pub fn committed_hooks_path(repo_root: &Path) -> PathBuf {
    repo_hooks_base(repo_root).join("hooks.toml")
}

/// Path to the local override TOML for a repo display name.
pub fn local_hooks_path(data_dir: &Path, repo: &str) -> PathBuf {
    data_dir.join("hooks").join(format!("{repo}.toml"))
}

/// Directory holding local scripts for a repo: `<data_dir>/hooks/<repo>/`.
pub fn local_hooks_base(data_dir: &Path, repo: &str) -> PathBuf {
    data_dir.join("hooks").join(repo)
}

/// Canonical repo scripts dir: `<repo>/.openorchestra/scripts/`.
pub fn repo_scripts_dir(repo_root: &Path) -> PathBuf {
    repo_hooks_base(repo_root).join("scripts")
}

/// Canonical local scripts dir: `<data_dir>/hooks/<repo>/scripts/`.
pub fn local_scripts_dir(data_dir: &Path, repo: &str) -> PathBuf {
    local_hooks_base(data_dir, repo).join("scripts")
}

/// Absolute path of the canonical script for a layer + phase.
pub fn hook_script_path(
    layer: HookLayer,
    phase: HookScriptPhase,
    repo_root: &Path,
    data_dir: &Path,
    repo: &str,
) -> PathBuf {
    let dir = match layer {
        HookLayer::Repo => repo_scripts_dir(repo_root),
        HookLayer::Local => local_scripts_dir(data_dir, repo),
    };
    dir.join(phase.file_name())
}

/// Relative path written into generated TOML (`scripts/setup.sh`).
fn canonical_rel(phase: HookScriptPhase) -> String {
    format!("scripts/{}", phase.file_name())
}

fn script_template(phase: HookScriptPhase) -> String {
    format!(
        r#"#!/usr/bin/env bash
# openOrchestra {phase} hook — runs with cwd = the member worktree.
# Env (set by the harness):
#   HARNESS_REPO_ROOT      main checkout of this project
#   HARNESS_WORKTREE       member worktree path (also cwd)
#   HARNESS_BRANCH         member branch
#   HARNESS_TASK_SLUG      task slug
#   HARNESS_TASK_ID        task id (multi-member tasks)
#   HARNESS_HOME_WORKTREE  home member path (multi-member tasks)
#   HARNESS_TASK_CONTEXT   path to agent-context.md (multi-member tasks)
set -euo pipefail

# Add your {phase} steps below.
"#,
        phase = phase.label()
    )
}

fn load_file(path: &Path) -> Result<Option<HooksFile>, HooksError> {
    match fs::read_to_string(path) {
        Ok(text) => {
            let file: HooksFile = toml::from_str(&text)
                .map_err(|e| HooksError::Parse(format!("{path:?}: {e}")))?;
            Ok(Some(file))
        }
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(HooksError::Io(e)),
    }
}

fn write_hooks_toml(path: &Path, file: &HooksFile) -> Result<(), HooksError> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    let text = toml::to_string_pretty(file)
        .map_err(|e| HooksError::Parse(format!("serialize {path:?}: {e}")))?;
    fs::write(path, text)?;
    Ok(())
}

fn resolve_scripts(base: &Path, scripts: &[String]) -> Vec<PathBuf> {
    scripts
        .iter()
        .map(|s| {
            let p = Path::new(s);
            if p.is_absolute() {
                p.to_path_buf()
            } else {
                base.join(p)
            }
        })
        .collect()
}

/// [`resolve_scripts`] for the repo-committed layer, which arrives with the
/// repository and so is not something the user wrote.
///
/// Every entry must stay inside `<repo>/.openorchestra/`: no absolute paths,
/// no `..`, and no symlink that resolves outside. Otherwise `hooks.toml` could
/// run a file that is not in the repository at all (`/tmp/x.sh`,
/// `../../../somewhere`), so reviewing the repo's own scripts would not tell
/// you what runs. An escaping entry is an error rather than silently skipped,
/// so a broken config is visible instead of half-applied.
fn resolve_contained_scripts(base: &Path, scripts: &[String]) -> Result<Vec<PathBuf>, HooksError> {
    use std::path::Component;
    let canonical_base = base.canonicalize().unwrap_or_else(|_| base.to_path_buf());
    scripts
        .iter()
        .map(|s| {
            let p = Path::new(s);
            let lexically_inside = p
                .components()
                .all(|c| matches!(c, Component::Normal(_) | Component::CurDir));
            let joined = base.join(p);
            // Resolve the deepest part that exists: a symlinked *directory*
            // escapes even when the script under it does not exist yet.
            let resolved_inside = joined
                .ancestors()
                .find_map(|a| a.canonicalize().ok())
                .is_none_or(|real| real.starts_with(&canonical_base));
            if lexically_inside && resolved_inside {
                Ok(joined)
            } else {
                Err(HooksError::Parse(format!(
                    "hook script {s:?} is outside {} — committed hooks may only run scripts inside it",
                    base.display()
                )))
            }
        })
        .collect()
}

/// Prefer local phases entirely when a local file exists (replace, not append).
pub fn merge_hooks_replace(committed: &HooksFile, local: Option<&HooksFile>) -> HooksFile {
    match local {
        None => committed.clone(),
        Some(local) => HooksFile {
            setup: local.setup.clone(),
            teardown: local.teardown.clone(),
        },
    }
}

/// Create the canonical script (and its TOML entry) if missing; return its path.
///
/// Does not overwrite an existing script body. Updates the layer's TOML so the
/// phase lists the canonical relative path (preserving the other phase).
pub fn ensure_hook_script(
    layer: HookLayer,
    phase: HookScriptPhase,
    repo_root: &Path,
    data_dir: &Path,
    repo: &str,
) -> Result<PathBuf, HooksError> {
    let script = hook_script_path(layer, phase, repo_root, data_dir, repo);
    if let Some(parent) = script.parent() {
        fs::create_dir_all(parent)?;
    }
    if !script.is_file() {
        fs::write(&script, script_template(phase))?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mut perms = fs::metadata(&script)?.permissions();
            perms.set_mode(0o755);
            fs::set_permissions(&script, perms)?;
        }
    }

    let toml_path = match layer {
        HookLayer::Repo => committed_hooks_path(repo_root),
        HookLayer::Local => local_hooks_path(data_dir, repo),
    };
    let mut file = load_file(&toml_path)?.unwrap_or_default();
    let rel = canonical_rel(phase);
    match phase {
        HookScriptPhase::Setup => {
            if !file.setup.scripts.iter().any(|s| s == &rel) {
                file.setup.scripts = vec![rel];
            }
        }
        HookScriptPhase::Teardown => {
            if !file.teardown.scripts.iter().any(|s| s == &rel) {
                file.teardown.scripts = vec![rel];
            }
        }
    }
    write_hooks_toml(&toml_path, &file)?;
    Ok(script)
}

/// Remove the machine-local override for a repo: TOML plus scripts directory.
///
/// After this, [`HooksConfig::load`] falls back to the committed hooks (if any).
/// Does not touch the repo checkout.
pub fn clear_local_hooks(data_dir: &Path, repo: &str) -> Result<(), HooksError> {
    let toml = local_hooks_path(data_dir, repo);
    if toml.is_file() {
        fs::remove_file(&toml)?;
    }
    let base = local_hooks_base(data_dir, repo);
    if base.is_dir() {
        fs::remove_dir_all(&base)?;
    }
    Ok(())
}

/// Whether `path` is a harness-managed hooks script for this repo.
pub fn classify_hook_script(
    path: &Path,
    repo_root: &Path,
    data_dir: &Path,
    repo: &str,
) -> Option<(HookLayer, HookScriptPhase)> {
    let path = path.canonicalize().unwrap_or_else(|_| path.to_path_buf());
    for phase in [HookScriptPhase::Setup, HookScriptPhase::Teardown] {
        let repo_p = hook_script_path(HookLayer::Repo, phase, repo_root, data_dir, repo);
        let repo_c = repo_p.canonicalize().unwrap_or(repo_p);
        if path == repo_c {
            return Some((HookLayer::Repo, phase));
        }
        let local_p = hook_script_path(HookLayer::Local, phase, repo_root, data_dir, repo);
        let local_c = local_p.canonicalize().unwrap_or(local_p);
        if path == local_c {
            return Some((HookLayer::Local, phase));
        }
    }
    None
}

impl HooksConfig {
    /// Load committed + optional local override and resolve script paths.
    ///
    /// Relative scripts resolve from the directory of the TOML they came from:
    /// `<data_dir>/hooks/<repo>/` when a local override exists, otherwise
    /// `<repo_root>/.openorchestra/`. Either way the canonical
    /// `scripts/<phase>.sh` entry lands in that layer's scripts dir.
    pub fn load(repo_root: &Path, data_dir: &Path, repo: &str) -> Result<Self, HooksError> {
        let committed = load_file(&committed_hooks_path(repo_root))?.unwrap_or_default();
        let local = load_file(&local_hooks_path(data_dir, repo))?;
        let using_local = local.is_some();
        let merged = merge_hooks_replace(&committed, local.as_ref());
        let base = if using_local {
            local_hooks_base(data_dir, repo)
        } else {
            repo_hooks_base(repo_root)
        };
        let resolve = |scripts: &[String]| {
            if using_local {
                Ok(resolve_scripts(&base, scripts))
            } else {
                resolve_contained_scripts(&base, scripts)
            }
        };
        Ok(HooksConfig {
            setup: resolve(&merged.setup.scripts)?,
            teardown: resolve(&merged.teardown.scripts)?,
        })
    }

    /// Shell command lines to run setup scripts (cwd should be the worktree).
    pub fn setup_shell_commands(&self, env: &HookEnv) -> Vec<String> {
        shell_commands_for(&self.setup, env)
    }

    /// Per-line steps for a visible shell (exports then scripts). Prefer this
    /// over [`Self::setup_shell_commands`] when driving tmux send-keys.
    pub fn setup_shell_steps(&self, env: &HookEnv) -> Vec<String> {
        setup_shell_steps(&self.setup, env)
    }

    pub fn teardown_shell_commands(&self, env: &HookEnv) -> Vec<String> {
        shell_commands_for(&self.teardown, env)
    }

    pub fn run_setup<R: CommandRunner>(
        &self,
        runner: &R,
        env: &HookEnv,
    ) -> Result<(), HooksError> {
        run_scripts(runner, &self.setup, env)
    }

    pub fn run_teardown<R: CommandRunner>(
        &self,
        runner: &R,
        env: &HookEnv,
    ) -> Result<(), HooksError> {
        run_scripts(runner, &self.teardown, env)
    }
}

fn shell_commands_for(scripts: &[PathBuf], env: &HookEnv) -> Vec<String> {
    // One shell line per script: exports + cd + invoke. Callers that drive a
    // visible tty (tmux send-keys) should prefer [`setup_shell_steps`] so each
    // export is its own Enter — long single lines silently truncate.
    let exports: String = env
        .to_map()
        .iter()
        .map(|(k, v)| format!("export {k}={}", shell_quote(v)))
        .collect::<Vec<_>>()
        .join("; ");
    let cwd = shell_quote(&env.worktree.to_string_lossy());
    scripts
        .iter()
        .map(|script| {
            let script_q = shell_quote(&script.to_string_lossy());
            if exports.is_empty() {
                format!("cd {cwd} && {script_q}")
            } else {
                format!("{exports}; cd {cwd} && {script_q}")
            }
        })
        .collect()
}

/// Visible-shell steps for one member's setup: each export is its own line,
/// then `cd` + script. Prefer [`write_visible_setup_runner`] + one tmux
/// `send-keys` — rapid per-line send-keys race interactive shells.
pub fn setup_shell_steps(scripts: &[PathBuf], env: &HookEnv) -> Vec<String> {
    let mut steps = Vec::new();
    // Stable order so the terminal transcript is readable.
    let mut keys: Vec<_> = env.to_map().into_iter().collect();
    keys.sort_by(|a, b| a.0.cmp(&b.0));
    for (k, v) in keys {
        steps.push(format!("export {k}={}", shell_quote(&v)));
    }
    let cwd = shell_quote(&env.worktree.to_string_lossy());
    for script in scripts {
        let script_q = shell_quote(&script.to_string_lossy());
        steps.push(format!("cd {cwd} && {script_q}"));
    }
    steps
}

/// One shell line of `export K=V; …` for `env` (stable key order).
pub fn shell_export_line(env: &HookEnv) -> String {
    let mut keys: Vec<_> = env.to_map().into_iter().collect();
    keys.sort_by(|a, b| a.0.cmp(&b.0));
    keys.into_iter()
        .map(|(k, v)| format!("export {k}={}", shell_quote(&v)))
        .collect::<Vec<_>>()
        .join("; ")
}

/// POSIX sh body that runs task + per-member setup scripts with brief banners.
///
/// Designed to be written to disk and invoked with a single interactive
/// `sh '<path>'` so tmux send-keys cannot interleave with the prompt.
pub fn format_visible_setup_runner(
    task_setup: Option<&Path>,
    member_paths: &[(String, PathBuf)],
    members: &[(HookEnv, Vec<PathBuf>)],
) -> String {
    // Leading blank line: the invoking command wraps over several terminal
    // rows, so the banner needs air to read as the start of the block.
    let mut out = String::from(
        "#!/bin/sh\n# Generated by openOrchestra — do not edit.\necho ''\necho '=== openOrchestra setup ==='\nstatus=0\n",
    );
    if let Some(script) = task_setup {
        out.push_str("echo '+ task setup'\n");
        // Reuse the same export+invoke shape as TaskHooks::setup_shell_command.
        out.push_str(&task_hook_command(script, member_paths));
        out.push_str(" || status=$?\n");
    }
    for (env, scripts) in members {
        if scripts.is_empty() {
            continue;
        }
        out.push_str(&format!(
            "echo '+ setup {}'\n",
            env.worktree
                .file_name()
                .and_then(|s| s.to_str())
                .unwrap_or("member")
                .replace('\'', "")
        ));
        let mut keys: Vec<_> = env.to_map().into_iter().collect();
        keys.sort_by(|a, b| a.0.cmp(&b.0));
        for (k, v) in keys {
            out.push_str(&format!("export {k}={}\n", shell_quote(&v)));
        }
        let cwd = shell_quote(&env.worktree.to_string_lossy());
        out.push_str(&format!("cd {cwd} || status=$?\n"));
        for script in scripts {
            let script_q = shell_quote(&script.to_string_lossy());
            out.push_str(&format!(
                "echo {}\n",
                shell_quote(&format!("  > {}", script.display()))
            ));
            out.push_str(&format!("{script_q} || status=$?\n"));
        }
    }
    // Exit code only when it carries information — a bare 0 is noise.
    out.push_str(
        "if [ \"$status\" -eq 0 ]; then\n  echo '=== setup finished ==='\nelse\n  echo \"=== setup FAILED (exit $status) ===\"\nfi\nexit \"$status\"\n",
    );
    out
}

/// Write [`format_visible_setup_runner`] to `out` (creates parent dirs).
pub fn write_visible_setup_runner(
    out: &Path,
    task_setup: Option<&Path>,
    member_paths: &[(String, PathBuf)],
    members: &[(HookEnv, Vec<PathBuf>)],
) -> Result<(), HooksError> {
    if let Some(parent) = out.parent() {
        fs::create_dir_all(parent)?;
    }
    let body = format_visible_setup_runner(task_setup, member_paths, members);
    fs::write(out, body)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mut perms = fs::metadata(out)?.permissions();
        perms.set_mode(0o755);
        fs::set_permissions(out, perms)?;
    }
    Ok(())
}

/// Single interactive shell line that runs the runner — nothing else.
///
/// `HARNESS_*` reach the user's shell as the tmux pane's inherited environment
/// (`new-session -e`), not as typed `export`s: a typed export tail wraps over
/// several terminal rows and buries the setup output, and its POSIX syntax
/// would not parse under a fish login shell.
pub fn visible_setup_shell_line(runner: &Path) -> String {
    format!("sh {}", shell_quote(&runner.to_string_lossy()))
}

fn shell_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// Run one shell line the way the user's terminal would.
///
/// Hook scripts are the code most likely to reach for a tool that only exists
/// after `.zshrc` runs — `nvm`, `bun`, `conda`, a `pyenv` shim — so they get the
/// same login+interactive shell as everything else rather than a bare `sh -lc`.
fn run_in_login_shell<R: CommandRunner>(
    runner: &R,
    cwd: Option<&Path>,
    cmdline: &str,
) -> io::Result<CommandOutput> {
    let (program, args) = crate::login_shell::interactive_login_command(cmdline);
    let args: Vec<&str> = args.iter().map(String::as_str).collect();
    runner.run(cwd, &program, &args)
}

fn run_scripts<R: CommandRunner>(
    runner: &R,
    scripts: &[PathBuf],
    env: &HookEnv,
) -> Result<(), HooksError> {
    for script in scripts {
        let mut exports = String::new();
        for (k, v) in env.to_map() {
            exports.push_str(&format!("export {k}={}; ", shell_quote(&v)));
        }
        let cmdline = format!(
            "{exports}exec {}",
            shell_quote(&script.to_string_lossy())
        );
        let out = run_in_login_shell(runner, Some(&env.worktree), &cmdline)?;
        if !out.success() {
            return Err(HooksError::ScriptFailed {
                script: script.clone(),
                status: out.status,
                stderr: out.stderr,
            });
        }
    }
    Ok(())
}

/// Load task-level scripts from `~/.openorchestra/tasks/<slug>/`.
#[derive(Debug, Clone, Default)]
pub struct TaskHooks {
    pub setup: Option<PathBuf>,
    pub teardown: Option<PathBuf>,
}

impl TaskHooks {
    pub fn load(data_dir: &Path, task_slug: &str) -> Self {
        let dir = data_dir.join("tasks").join(task_slug);
        let setup = dir.join("setup.sh");
        let teardown = dir.join("teardown.sh");
        TaskHooks {
            setup: setup.is_file().then_some(setup),
            teardown: teardown.is_file().then_some(teardown),
        }
    }

    pub fn setup_shell_command(&self, member_paths: &[(String, PathBuf)]) -> Option<String> {
        let script = self.setup.as_ref()?;
        Some(task_hook_command(script, member_paths))
    }

    pub fn teardown_shell_command(&self, member_paths: &[(String, PathBuf)]) -> Option<String> {
        let script = self.teardown.as_ref()?;
        Some(task_hook_command(script, member_paths))
    }

    pub fn run_setup<R: CommandRunner>(
        &self,
        runner: &R,
        cwd: &Path,
        member_paths: &[(String, PathBuf)],
    ) -> Result<(), HooksError> {
        let Some(script) = &self.setup else {
            return Ok(());
        };
        run_task_script(runner, script, cwd, member_paths)
    }

    pub fn run_teardown<R: CommandRunner>(
        &self,
        runner: &R,
        cwd: &Path,
        member_paths: &[(String, PathBuf)],
    ) -> Result<(), HooksError> {
        let Some(script) = &self.teardown else {
            return Ok(());
        };
        run_task_script(runner, script, cwd, member_paths)
    }
}

/// `HARNESS_MEMBER_<REPO>` for a project name. The name is a directory name,
/// so it can hold any character — including `;`, `=` and spaces, which would
/// turn `export <key>=…` into extra shell commands. Only `[A-Z0-9_]` is kept;
/// everything else becomes `_`, so `my-app` stays `MY_APP` as before.
fn member_env_key(repo: &str) -> String {
    let name: String = repo
        .chars()
        .map(|c| {
            let c = c.to_ascii_uppercase();
            if c.is_ascii_uppercase() || c.is_ascii_digit() { c } else { '_' }
        })
        .collect();
    format!("HARNESS_MEMBER_{name}")
}

fn task_hook_command(script: &Path, member_paths: &[(String, PathBuf)]) -> String {
    let mut exports = String::new();
    for (repo, path) in member_paths {
        let key = member_env_key(repo);
        exports.push_str(&format!(
            "export {key}={}; ",
            shell_quote(&path.to_string_lossy())
        ));
    }
    format!("{exports}{}", shell_quote(&script.to_string_lossy()))
}

fn run_task_script<R: CommandRunner>(
    runner: &R,
    script: &Path,
    cwd: &Path,
    member_paths: &[(String, PathBuf)],
) -> Result<(), HooksError> {
    let cmdline = task_hook_command(script, member_paths);
    let out = run_in_login_shell(runner, Some(cwd), &cmdline)?;
    if !out.success() {
        return Err(HooksError::ScriptFailed {
            script: script.to_path_buf(),
            status: out.status,
            stderr: out.stderr,
        });
    }
    Ok(())
}

#[cfg(test)]
mod hardening_tests {
    use super::*;

    #[test]
    fn a_project_name_cannot_inject_shell_into_the_member_export() {
        assert_eq!(member_env_key("my-app"), "HARNESS_MEMBER_MY_APP");
        let key = member_env_key("a=1;touch ~/.pwn;b");
        assert!(key.chars().all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_'), "{key}");
        let cmd = task_hook_command(Path::new("/s.sh"), &[("a=1;touch x;b".into(), PathBuf::from("/wt"))]);
        assert_eq!(cmd.matches(';').count(), 1, "only the separator after the export: {cmd}");
    }

    #[test]
    fn committed_hooks_cannot_point_outside_their_folder() {
        let tmp = tempfile::tempdir().unwrap();
        let base = tmp.path().join(".openorchestra");
        fs::create_dir_all(base.join("scripts")).unwrap();
        assert!(resolve_contained_scripts(&base, &["scripts/setup.sh".into()]).is_ok());
        assert!(resolve_contained_scripts(&base, &["/tmp/x.sh".into()]).is_err());
        assert!(resolve_contained_scripts(&base, &["../../x.sh".into()]).is_err());
        #[cfg(unix)]
        {
            std::os::unix::fs::symlink("/tmp", base.join("scripts/out")).unwrap();
            assert!(resolve_contained_scripts(&base, &["scripts/out/x.sh".into()]).is_err());
        }
    }
}

