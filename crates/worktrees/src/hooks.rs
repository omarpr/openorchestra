    fn visible_setup_runner_invokes_script_and_shell_line_is_one_command() {
        let tmp = tempfile::tempdir().unwrap();
        let script = tmp.path().join("setup.sh");
        fs::write(&script, "#!/bin/sh\necho hi-from-setup\n").unwrap();
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mut perms = fs::metadata(&script).unwrap().permissions();
            perms.set_mode(0o755);
            fs::set_permissions(&script, perms).unwrap();
        }
        let env = HookEnv {
            repo_root: PathBuf::from("/repo"),
            worktree: tmp.path().to_path_buf(),
            branch: "feat".into(),
            task_slug: "slug".into(),
            task_id: Some("tid".into()),
            home_worktree: Some(tmp.path().to_path_buf()),
        };
        let runner = tmp.path().join("run.sh");
        write_visible_setup_runner(&runner, None, &[], &[(env.clone(), vec![script])]).unwrap();
        let body = fs::read_to_string(&runner).unwrap();
        assert!(body.contains("=== openOrchestra setup ==="));
        assert!(body.contains("hi-from-setup") || body.contains("setup.sh"));
        assert!(body.contains("export HARNESS_WORKTREE="));

        let line = visible_setup_shell_line(&runner);
        assert!(line.starts_with("sh '"));
        // Nothing but the runner: the export tail wrapped over several rows and
        // buried the output. HARNESS_* now arrive via the tmux pane env.
        assert!(!line.contains("export"), "{line}");
        // One interactive submission — no newlines for send-keys to split on.
        assert!(!line.contains('\n'));

        let out = std::process::Command::new("sh")
            .arg(&runner)
            .output()
            .unwrap();
        let stdout = String::from_utf8_lossy(&out.stdout);
        assert!(out.status.success(), "stderr={}", String::from_utf8_lossy(&out.stderr));
        assert!(stdout.contains("hi-from-setup"), "{stdout}");
        // Success says nothing about exit codes; a bare 0 is noise.
        assert!(stdout.contains("=== setup finished ==="), "{stdout}");
        assert!(!stdout.contains("exit 0"), "{stdout}");
        // Banner is preceded by a blank line so it reads as a block start.
        assert!(stdout.starts_with("\n=== openOrchestra setup ==="), "{stdout}");
    }

